-- RESCATA
-- Esquema para Oracle (12c o superior), listo para importar en SQL Developer Data Modeler
-- Orden: 1) catalogos  2) tablas principales  3) claves foraneas

-- =========================================================
-- 1) CATALOGOS
-- =========================================================

CREATE TABLE distrito (
  id_distrito     NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY,
  nombre_distrito VARCHAR2(80) NOT NULL,
  provincia       VARCHAR2(80) DEFAULT 'LIMA' NOT NULL,
  CONSTRAINT pk_distrito PRIMARY KEY (id_distrito),
  CONSTRAINT uq_distrito_nombre UNIQUE (nombre_distrito)
);

CREATE TABLE zona (
  id_zona     NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
  id_distrito NUMBER(10)    NOT NULL,
  zona_nombre VARCHAR2(100) NOT NULL,
  CONSTRAINT pk_zona PRIMARY KEY (id_zona),
  CONSTRAINT uq_zona_distrito_nombre UNIQUE (id_distrito, zona_nombre)
);

CREATE TABLE estadoDonante (
  id_estadoDonante NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY,
  estado           VARCHAR2(30) NOT NULL,
  CONSTRAINT pk_estadoDonante PRIMARY KEY (id_estadoDonante),
  CONSTRAINT uq_estadoDonante UNIQUE (estado)
);

CREATE TABLE organizacionTipo (
  id_organizacionTipo NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY,
  tipo                VARCHAR2(50) NOT NULL,
  CONSTRAINT pk_organizacionTipo PRIMARY KEY (id_organizacionTipo),
  CONSTRAINT uq_organizacionTipo UNIQUE (tipo)
);

CREATE TABLE organizacionEstado (
  id_organizacionEstado NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY,
  estado                VARCHAR2(30) NOT NULL,
  CONSTRAINT pk_organizacionEstado PRIMARY KEY (id_organizacionEstado),
  CONSTRAINT uq_organizacionEstado UNIQUE (estado)
);

CREATE TABLE donacionLoteEstado (
  id_donacionLoteEstado NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY,
  estadoLote            VARCHAR2(30) NOT NULL,
  CONSTRAINT pk_donacionLoteEstado PRIMARY KEY (id_donacionLoteEstado),
  CONSTRAINT uq_donacionLoteEstado UNIQUE (estadoLote)
);

CREATE TABLE donacionEstado (
  id_donacionEstado NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY,
  estado            VARCHAR2(30) NOT NULL,
  CONSTRAINT pk_donacionEstado PRIMARY KEY (id_donacionEstado),
  CONSTRAINT uq_donacionEstado UNIQUE (estado)
);

CREATE TABLE tipoDocumento (
  id_tipoDocumento NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY,
  tipoDoc          VARCHAR2(30) NOT NULL,
  CONSTRAINT pk_tipoDocumento PRIMARY KEY (id_tipoDocumento),
  CONSTRAINT uq_tipoDocumento UNIQUE (tipoDoc)
);

CREATE TABLE medidaCantidad (
  id_medidaCantidad NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY,
  tipoMedida        VARCHAR2(30) NOT NULL,
  CONSTRAINT pk_medidaCantidad PRIMARY KEY (id_medidaCantidad),
  CONSTRAINT uq_medidaCantidad UNIQUE (tipoMedida)
);

CREATE TABLE categoriaAlimento (
  id_categoria     NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY,
  nombre_categoria VARCHAR2(50) NOT NULL,
  CONSTRAINT pk_categoriaAlimento PRIMARY KEY (id_categoria),
  CONSTRAINT uq_categoriaAlimento UNIQUE (nombre_categoria)
);

-- =========================================================
-- 2) TABLAS PRINCIPALES
-- =========================================================

CREATE TABLE alimento (
  id_alimento            NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
  nombre_alimento        VARCHAR2(150) NOT NULL,
  id_categoria           NUMBER(10)    NOT NULL,
  requiere_refrigeracion NUMBER(1)     DEFAULT 0 NOT NULL,
  CONSTRAINT pk_alimento PRIMARY KEY (id_alimento),
  CONSTRAINT uq_alimento_nombre UNIQUE (nombre_alimento),
  CONSTRAINT ck_alimento_refrig CHECK (requiere_refrigeracion IN (0, 1))
);

CREATE TABLE donante (
  id_donante       NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
  nombre_donante   VARCHAR2(150) NOT NULL,
  direccion        VARCHAR2(200),
  id_zona          NUMBER(10),
  telefono         VARCHAR2(30),
  email            VARCHAR2(100),
  id_estadoDonante NUMBER(10)    NOT NULL,
  CONSTRAINT pk_donante PRIMARY KEY (id_donante)
);

CREATE TABLE organizacion (
  id_organizacion       NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
  nombre_organizacion   VARCHAR2(150) NOT NULL,
  direccion             VARCHAR2(200),
  id_zona               NUMBER(10),
  fecha_habilitacion    DATE          DEFAULT SYSDATE,
  id_organizacionEstado NUMBER(10)    NOT NULL,
  id_organizacionTipo   NUMBER(10)    NOT NULL,
  CONSTRAINT pk_organizacion PRIMARY KEY (id_organizacion)
);

CREATE TABLE donacionLote (
  id_donacionLote       NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
  id_donante            NUMBER(10)    NOT NULL,
  fechaPublicacion      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  id_donacionLoteEstado NUMBER(10)    NOT NULL,
  direccion             VARCHAR2(200),
  id_zona               NUMBER(10),
  CONSTRAINT pk_donacionLote PRIMARY KEY (id_donacionLote)
);

CREATE TABLE donacionLoteDetalle (
  id_donacionLoteDetalle NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY,
  id_donacionLote        NUMBER(10)   NOT NULL,
  id_alimento            NUMBER(10)   NOT NULL,
  marca                  VARCHAR2(80),
  codigoLote             VARCHAR2(50),
  fechaVencimiento       DATE,
  cantidad               NUMBER(10,2) NOT NULL,
  id_medidaCantidad      NUMBER(10)   NOT NULL,
  pesoTotalKg            NUMBER(10,2),
  costoUnitario          NUMBER(10,2) NOT NULL,
  CONSTRAINT pk_donacionLoteDetalle PRIMARY KEY (id_donacionLoteDetalle),
  CONSTRAINT ck_loteDet_cantidad CHECK (cantidad > 0),
  CONSTRAINT ck_loteDet_peso CHECK (pesoTotalKg > 0),
  CONSTRAINT ck_loteDet_costo CHECK (costoUnitario >= 0)
);

CREATE TABLE donacion (
  id_donacion       NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  id_donacionLote   NUMBER(10) NOT NULL,
  id_organizacion   NUMBER(10) NOT NULL,
  fechaSolicitud    TIMESTAMP  DEFAULT SYSTIMESTAMP NOT NULL,
  id_donacionEstado NUMBER(10) NOT NULL,
  CONSTRAINT pk_donacion PRIMARY KEY (id_donacion)
);

CREATE TABLE donacionDetalle (
  id_donacionDetalle     NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY,
  id_donacion            NUMBER(10)   NOT NULL,
  id_donacionLoteDetalle NUMBER(10)   NOT NULL,
  cantidad               NUMBER(10,2) NOT NULL,
  CONSTRAINT pk_donacionDetalle PRIMARY KEY (id_donacionDetalle),
  CONSTRAINT uq_donDet_donacion_linea UNIQUE (id_donacion, id_donacionLoteDetalle),
  CONSTRAINT ck_donDet_cantidad CHECK (cantidad > 0)
);

CREATE TABLE personaRecojo (
  id_personaRecojo NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
  id_organizacion  NUMBER(10)    NOT NULL,
  nombres          VARCHAR2(100) NOT NULL,
  apellidos        VARCHAR2(100) NOT NULL,
  id_tipoDocumento NUMBER(10)    NOT NULL,
  numDocumento     VARCHAR2(15)  NOT NULL,
  sexo             VARCHAR2(1),
  telefono         VARCHAR2(30),
  email            VARCHAR2(100),
  CONSTRAINT pk_personaRecojo PRIMARY KEY (id_personaRecojo),
  CONSTRAINT uq_persona_org_doc UNIQUE (id_organizacion, id_tipoDocumento, numDocumento),
  CONSTRAINT ck_persona_sexo CHECK (sexo IN ('M', 'F'))
);

CREATE TABLE despachoRecojo (
  id_despachoRecojo NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
  id_donacion       NUMBER(10)    NOT NULL,
  vehiculo          VARCHAR2(100),
  fechaProgramada   TIMESTAMP     NOT NULL,
  fechaLlegada      TIMESTAMP,
  fechaSalida       TIMESTAMP,
  fechaArribo       TIMESTAMP,
  CONSTRAINT pk_despachoRecojo PRIMARY KEY (id_despachoRecojo),
  CONSTRAINT ck_despacho_salida CHECK (fechaSalida >= fechaLlegada),
  CONSTRAINT ck_despacho_arribo CHECK (fechaArribo >= fechaSalida)
);

CREATE TABLE detalleResponsableRecojo (
  id_responsableRecojo NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
  id_despachoRecojo    NUMBER(10) NOT NULL,
  id_personaRecojo     NUMBER(10) NOT NULL,
  CONSTRAINT pk_detalleResponsableRecojo PRIMARY KEY (id_responsableRecojo),
  CONSTRAINT uq_detResp_despacho_persona UNIQUE (id_despachoRecojo, id_personaRecojo)
);

CREATE TABLE comprobante (
  id_comprobante NUMBER(10)  GENERATED BY DEFAULT AS IDENTITY,
  id_donacion    NUMBER(10)  NOT NULL,
  serie          VARCHAR2(4) NOT NULL,
  numero         NUMBER(8)   NOT NULL,
  fechaEmision   TIMESTAMP   DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_comprobante PRIMARY KEY (id_comprobante),
  CONSTRAINT uq_comprobante_serie_numero UNIQUE (serie, numero)
);

